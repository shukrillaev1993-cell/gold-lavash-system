/**
 * Убирает markdown-разметку и эмодзи из текста перед озвучкой — иначе TTS
 * зачитывает "звёздочка звёздочка", названия эмодзи и т.п. буквально.
 * НЕ используется для отображаемого текста в чате — только перед синтезом речи.
 */
export function sanitizeForSpeech(text: string): string {
  return text
    .replace(/```[\s\S]*?```/g, " ") // код-блоки целиком — не зачитываем код
    .replace(/`([^`]+)`/g, "$1") // инлайн-код
    .replace(/\*\*([^*]+)\*\*/g, "$1") // **жирный**
    .replace(/\*([^*]+)\*/g, "$1") // *курсив*
    .replace(/__([^_]+)__/g, "$1") // __жирный__
    .replace(/_([^_]+)_/g, "$1") // _курсив_
    .replace(/^#{1,6}\s+/gm, "") // # заголовки
    .replace(/^[ \t]*[-*+]\s+/gm, "") // - маркеры списков
    .replace(/^[ \t]*\d+\.\s+/gm, "") // 1. нумерованные списки
    .replace(/\[([^\]]+)\]\([^)]+\)/g, "$1") // [текст](ссылка)
    .replace(/[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}\u{2300}-\u{23FF}\u{2190}-\u{21FF}\u{2B00}-\u{2BFF}\u{FE0F}]/gu, "")
    .replace(/\s+/g, " ")
    .trim();
}
